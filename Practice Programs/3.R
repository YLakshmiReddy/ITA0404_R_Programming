# Find the mean of numbers from 20 to 60
mean_val <- mean(20:60)
cat("Mean of numbers from 20 to 60:", mean_val, "\n")

# Find the sum of numbers from 51 to 91
sum_val <- sum(51:91)
cat("Sum of numbers from 51 to 91:", sum_val, "\n")